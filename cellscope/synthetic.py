"""Deterministic educational data, NEVER a replacement for real benchmarks."""
from __future__ import annotations
from pathlib import Path
import numpy as np
import pandas as pd


def generate_demo(path: str | Path, *, cells: int = 8, cycles: int = 30,
                  points: int = 75, seed: int = 42) -> dict:
    if min(cells, cycles, points) < 3:
        raise ValueError("Need at least three cells, cycles and points")
    rng = np.random.default_rng(seed)
    records = []
    for k in range(cells):
        eol_cycle = max(3, cycles - 5 + (k % 3))
        for cycle in range(1, cycles+1):
            soh = 1 - 0.20 * (cycle/eol_cycle)**1.28
            for t in range(points):
                soc = 1 - t/(points - 1)
                current = -1.3 - 0.23*np.sin(t/8 + k*0.31)
                voltage = 3.02 + 1.13*soc - 0.028*abs(current) + 0.02*(soh-1) + rng.normal(0, 0.003)
                temp = 24.5 + k*0.23 + 0.025*t + rng.normal(0, 0.05)
                records.append((f"CELL-{k+1:02d}", cycle, t, round(voltage, 6),
                                round(current, 6), round(temp, 6), round(soc, 6),
                                round(soh, 6), max(0, eol_cycle-cycle),
                                "synthetic-cycle"))
    dest = Path(path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    cols = ["cell_id", "cycle_index", "time_s", "voltage_v", "current_a", "temperature_c",
            "soc", "soh", "rul_cycles", "condition"]
    pd.DataFrame.from_records(records, columns=cols).to_csv(dest, index=False)
    return {"path": str(dest), "cells": cells, "cycles_per_cell": cycles,
            "rows": len(records), "seed": seed,
            "warning": "SYNTHETIC DATA: labels and EOL are generated by construction, not measured."}
