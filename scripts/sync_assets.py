"""Embed canonical public JSON as classic browser scripts for file:// support."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]


def main():
    pairs = [
        (ROOT / 'web/data/catalog.json', ROOT / 'web/assets/catalog.generated.js', 'CELLSCOPE_CATALOG'),
        (ROOT / 'web/data/demo_run.json', ROOT / 'web/assets/demo.generated.js', 'CELLSCOPE_DEMO_RUN'),
    ]
    for source, dest, variable in pairs:
        data = json.loads(source.read_text(encoding='utf-8'))
        dest.write_text('/* Generated by scripts/sync_assets.py. Do not edit. */\n'
                        f'window.{variable} = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n',
                        encoding='utf-8')
        print(f'Generated {dest.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
